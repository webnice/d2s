/*

	 Генератор Golang структур по структуре таблиц базы данных.

	 Документ описывает сопоставление типов данных MySQL и Golang, механизмы
	 переопределения типов полей и приводит примеры использования генератора
	 db2struct.

	 # Сопоставление типов данных MySQL → Golang

	 Сопоставление реализовано в mysql/mysql.go (columnTypeMapping) и
	 types/constants.go (typesMap). Для nullable колонок вместо скалярных типов
	 используются nullable-обёртки библиотеки github.com/webnice/nix/v2
	 (поле Valid равно false при NULL). Все типы nix/v2 реализуют интерфейсы
	 sql.Scanner и driver.Valuer, поэтому сгенерированные структуры совместимы
	 с database/sql, sqlx и gorm без дополнительного кода.

	 ## Целочисленные типы

		+--------------------------------------+------------------+------------------+
		| Тип MySQL                            | NOT NULL         | NULL             |
		+--------------------------------------+------------------+------------------+
		| tinyint(1), boolean, bool            | bool             | nix.Bool         |
		+--------------------------------------+------------------+------------------+
		| tinyint без ширины, tinyint(N>1)     | int8             | nix.Int8         |
		+--------------------------------------+------------------+------------------+
		| smallint                             | int16            | nix.Int16        |
		+--------------------------------------+------------------+------------------+
		| smallint unsigned                    | uint16           | nix.Uint16       |
		+--------------------------------------+------------------+------------------+
		| mediumint                            | int32            | nix.Int32        |
		+--------------------------------------+------------------+------------------+
		| mediumint unsigned                   | uint32           | nix.Uint32       |
		+--------------------------------------+------------------+------------------+
		| int                                  | int32            | nix.Int32        |
		+--------------------------------------+------------------+------------------+
		| int unsigned                         | uint32           | nix.Uint32       |
		+--------------------------------------+------------------+------------------+
		| bigint                               | int64            | nix.Int64        |
		+--------------------------------------+------------------+------------------+
		| bigint unsigned                      | uint64           | nix.Uint64       |
		+--------------------------------------+------------------+------------------+

	 Ширина tinyint определяется по COLUMN_TYPE: tinyint(1) — булев тип,
	 tinyint без ширины и tinyint(N>1) — числовой. Ширина остальных
	 целочисленных типов на тип Golang не влияет:
	 smallint всегда int16, mediumint и int — int32, bigint — int64.
	 Атрибут UNSIGNED определяется по COLUMN_TYPE и выбирает беззнаковый вариант.

	 ## Числа с плавающей точкой

		+--------------------------------------+------------------+------------------+
		| Тип MySQL                            | NOT NULL         | NULL             |
		+--------------------------------------+------------------+------------------+
		| float                                | float32          | nix.Float32      |
		+--------------------------------------+------------------+------------------+
		| float unsigned                       | float32          | nix.Float32      |
		+--------------------------------------+------------------+------------------+
		| double                               | float64          | nix.Float64      |
		+--------------------------------------+------------------+------------------+
		| double unsigned                      | float64          | nix.Float64      |
		+--------------------------------------+------------------+------------------+
		| decimal(p,0)                         | nix.BigInt       | nix.BigInt       |
		+--------------------------------------+------------------+------------------+
		| decimal(p,s>0)                       | float64          | nix.Float64      |
		+--------------------------------------+------------------+------------------+

	 decimal(p,0) сопоставляется с nix.BigInt (*big.Int) — целые десятичные
	 значения хранятся без потери точности, что важно для сумм в копейках.
	 decimal(p,s) с масштабом сопоставляется с float64 (с оговоркой о точности).
	 Атрибут UNSIGNED для float и double объявлен deprecated в MySQL 8.0.17+
	 и на сопоставление не влияет.

	 ## Битовые типы

		+--------------------------------------+------------------+------------------+
		| Тип MySQL                            | NOT NULL         | NULL             |
		+--------------------------------------+------------------+------------------+
		| bit(1)                               | bool             | nix.Bool         |
		+--------------------------------------+------------------+------------------+
		| bit(N>1)                             | []byte           | nix.Bytes        |
		+--------------------------------------+------------------+------------------+

	 Драйвер go-sql-driver отдаёт bit как []byte; bit(1) трактуется как булев
	 тип, bit(N>1) — как битовая строка.

	 ## Дата и время

		+--------------------------------------+------------------+------------------+
		| Тип MySQL                            | NOT NULL         | NULL             |
		+--------------------------------------+------------------+------------------+
		| date                                 | time.Time        | nix.Time         |
		+--------------------------------------+------------------+------------------+
		| datetime                             | time.Time        | nix.Time         |
		+--------------------------------------+------------------+------------------+
		| timestamp                            | time.Time        | nix.Time         |
		+--------------------------------------+------------------+------------------+
		| time                                 | time.Duration    | nix.Duration     |
		+--------------------------------------+------------------+------------------+
		| year                                 | int16            | nix.Int16        |
		+--------------------------------------+------------------+------------------+

	 MySQL TIME — длительность (-838:59:59..838:59:59), а не время суток,
	 поэтому сопоставляется с time.Duration и nix.Duration. Начиная с
	 nix/v2 v2.0.2, nix.Duration.Scan нативно разбирает формат времени баз
	 данных "[-][Ч]ЧЧ:ММ:СС[.дробная часть]" (MySQL TIME, PostgreSQL time),
	 включая []byte от go-sql-driver; для прочих строк работает fallback на
	 time.ParseDuration.

	 ## Строковые типы

		+--------------------------------------+------------------+------------------+
		| Тип MySQL                            | NOT NULL         | NULL             |
		+--------------------------------------+------------------+------------------+
		| char                                 | string           | nix.String       |
		+--------------------------------------+------------------+------------------+
		| varchar                              | string           | nix.String       |
		+--------------------------------------+------------------+------------------+
		| tinytext, text, mediumtext, longtext | string           | nix.String       |
		+--------------------------------------+------------------+------------------+
		| enum                                 | string           | nix.String       |
		+--------------------------------------+------------------+------------------+
		| set                                  | []string         | nix.StringSlice  |
		+--------------------------------------+------------------+------------------+

	 enum — скалярное одиночное значение, поэтому сопоставляется со строкой.
	 Драйвер отдаёт set строкой со значениями через запятую. Начиная с
	 nix/v2 v2.1.0, nix.StringSlice читает строковое представление set с
	 поддержкой экранирования (\, и \\), кодирует значение обратно при записи;
	 пустой слайс — пустая строка, нулевой объект — NULL.

	 ## Бинарные типы

		+--------------------------------------+------------------+------------------+
		| Тип MySQL                            | NOT NULL         | NULL             |
		+--------------------------------------+------------------+------------------+
		| binary                               | []byte           | nix.Bytes        |
		+--------------------------------------+------------------+------------------+
		| varbinary                            | []byte           | nix.Bytes        |
		+--------------------------------------+------------------+------------------+
		| tinyblob, blob, mediumblob, longblob | []byte           | nix.Bytes        |
		+--------------------------------------+------------------+------------------+

	 ## Прочие типы

		+--------------------------------------+------------------+------------------+
		| Тип MySQL                            | NOT NULL         | NULL             |
		+--------------------------------------+------------------+------------------+
		| json                                 | json.RawMessage  | nix.RawMessage   |
		+--------------------------------------+------------------+------------------+
		| geometry                             | []byte           | nix.Bytes        |
		+--------------------------------------+------------------+------------------+
		| point, linestring, polygon           | []byte           | nix.Bytes        |
		+--------------------------------------+------------------+------------------+
		| multipoint, multilinestring,         | []byte           | nix.Bytes        |
		+--------------------------------------+------------------+------------------+
		| multipolygon, geometrycollection     | []byte           | nix.Bytes        |
		+--------------------------------------+------------------+------------------+
		| uuid (MariaDB 10.7+)                 | nix.UUID         | nix.UUID         |
		+--------------------------------------+------------------+------------------+
		| inet4, inet6 (MariaDB 10.5+)         | nix.IP           | nix.IP           |
		+--------------------------------------+------------------+------------------+
		| vector (MariaDB 11.7+)               | []byte           | nix.Bytes        |
		+--------------------------------------+------------------+------------------+

	 Пространственные типы драйвер отдаёт как []byte во внутреннем бинарном
	 формате MySQL (WKB с 4-байтовым префиксом SRID); разбор WKB требует
	 внешней библиотеки, поэтому оставляются сырые байты.

	 ### MariaDB

	 Генератор протестирован с MariaDB 11.8: все основные типы данных
	 совместимы. Особенности MariaDB:

	   - JSON в MariaDB — псевдоним LONGTEXT с проверкой json_valid(), поэтому
	     INFORMATION_SCHEMA сообщает DATA_TYPE longtext и колонка сопоставляется
	     с string/nix.String. Для работы с JSON примените переопределение типа
	     {nix.RawMessage} в комментарии колонки или аргументом командной строки;
	   - Нативные типы MariaDB сопоставляются автоматически: uuid (10.7+) →
	     nix.UUID, inet4 и inet6 (10.5+) → nix.IP, vector (11.7+) → []byte;
	   - Неизвестный тип данных базы не прерывает генерацию: ошибка возникает
	     только если тип поля не переопределён через командную строку или
	     комментарий колонки.

	 Алиасы типов нормализуются самой базой: INFORMATION_SCHEMA.COLUMNS.DATA_TYPE
	 возвращает каноническое имя (integer → int, numeric/dec/fixed → decimal,
	 real/double precision → double, bool/boolean → tinyint,
	 geomcollection → geometrycollection), поэтому отдельные строки для алиасов
	 не требуются.

	 # Переопределение типов полей

	 Тип поля сгенерированной структуры можно переопределить двумя способами.
	 Переопределение применяется, только если поле базы данных указано и
	 совпадает; остальные поля генерируются по таблице сопоставления выше.

	 ## Через командную строку

	 В команду create добавляется необязательный шестой аргумент в самый конец —
	 список переопределений типов полей.

	 Синтаксис go:generate:

		//go:generate db2struct create "" "message" "types" "Message" "message_model.go" "поле1:тип;поле2:тип"

	 Пример:

		//go:generate db2struct create "" "message" "types" "Message" "message_model.go" "id:uint64;payload:nix.RawMessage;amount:nix.BigInt;created_at:time.Time"

	 Правила разбора:

	   - Пары разделяются ';', имя поля и тип — ':'.
	   - Пробелы вокруг пар и вокруг ':' отсекаются; пустые пары пропускаются.
	   - Имя поля — имя колонки базы данных (например snake_case), сравнение
	     без учёта регистра.
	   - Поле, отсутствующее в схеме таблицы, игнорируется (схема могла
	     измениться); в debug-режиме пишется в лог.
	   - Неизвестное имя типа — ошибка генерации со списком допустимых типов
	     (защита от опечаток).
	   - Пустой аргумент или отсутствие аргумента — сопоставление по умолчанию.

	 ## Через комментарий в базе данных

	 Если в комментарии к колонке (COLUMN_COMMENT) в любом месте (в начале, в конце,
	 в середине — не важно) встречается группа в фигурных скобках, содержимое
	 которой совпадает с одним из допустимых типов данных, — это считается
	 переопределением типа поля.

	 Примеры комментариев в базе данных:

		Время жизни сообщения {nix.Duration}
		{nix.Duration} Время жизни сообщения
		Время {nix.Duration} жизни сообщения

	 Правила разбора:

	   - Комментарий просматривается на наличие групп {...}; содержимое групп
	     отсекается по пробелам.
	   - Если таких групп несколько, берётся только первая группа, содержимое
	     которой совпадает с допустимым типом данных; остальные группы
	     игнорируются.
	   - Группы, содержимое которых не является допустимым типом данных,
	     игнорируются (например {примечание}).
	   - Список допустимых типов и nullable-правила — те же, что и для
	     переопределения через командную строку.
	   - Из сгенерированного комментария поля структуры сработавшая группа
	     {...} удаляется — в Golang код попадает только текст комментария.
	     Удаление выполняется независимо от того, какое переопределение
	     победило по приоритету.
	   - Сравнение типов выполняется без учёта регистра, в сгенерированный код
	     попадает каноническое имя типа (например {nix.duration} → nix.Duration).

	 ## Приоритет переопределений

	 При наличии нескольких переопределений для одного поля действует приоритет:

	   1. Командная строка — наивысший приоритет.
	   2. Комментарий к полю базы данных.
	   3. Базовый маппинг — сопоставление по умолчанию (таблицы выше).

	 ## Nullable-правила

	   - Указан базовый тип (bool, string, int64, time.Time, ...) и колонка
	     nullable — тип автоматически заменяется на соответствующую nix-обёртку
	     (bool → nix.Bool, time.Time → nix.Time и т.д.).
	   - Указан тип nix явно (nix.BigInt, nix.RawMessage, ...) — используется
	     как есть, для nullable и not null колонок.

	 ## Допустимые типы

		+-----------------------------+----------------------------------------------+
		| Стандартные типы Go         | Типы github.com/webnice/nix/v2               |
		+-----------------------------+----------------------------------------------+
		| bool                        | nix.Bool                                     |
		| string                      | nix.String                                   |
		| int, int8, int16, int32,    | nix.Int, nix.Int8, nix.Int16,                |
		| int64                       | nix.Int32, nix.Int64                         |
		| uint, uint8, uint16,        | nix.Uint, nix.Uint8, nix.Uint16,             |
		| uint32, uint64, uintptr     | nix.Uint32, nix.Uint64, nix.Uintptr          |
		| float32, float64            | nix.Float32, nix.Float64                     |
		| complex64, complex128       | nix.Complex64, nix.Complex128                |
		| []byte                      | nix.Bytes                                    |
		| []string                    | nix.StringSlice                              |
		| time.Time, time.Duration    | nix.Time, nix.Duration                       |
		| json.RawMessage             | nix.RawMessage, nix.BigInt, nix.UUID,        |
		|                             | nix.IP, nix.Nullable[T]                      |
		+-----------------------------+----------------------------------------------+

	 Дженерик nix.Nullable[T] допускает базовый скалярный тип из реестра:
	 nix.Nullable[string], nix.Nullable[int64] и т.д.

	 # Примеры использования

	 ## Простая генерация

		//go:generate db2struct create "" "message" "types" "Message" "message_model.go"

	 Аргументы команды create: [database] [table] [package] [struct] [file]
	 [types]. Имя базы данных можно оставить пустым — оно будет определено
	 из DSN строки соединения.

	 ## Переопределение через командную строку

		//go:generate db2struct create "" "message" "types" "Message" "message_model.go" "id:uint64;payload:nix.RawMessage;amount:nix.BigInt;created_at:time.Time"

	 ## Переопределение через комментарий в базе данных

		ALTER TABLE message MODIFY COLUMN ttl TIME NOT NULL COMMENT 'Время жизни {nix.Duration}';
		ALTER TABLE message MODIFY COLUMN amount DECIMAL(20,0) NOT NULL COMMENT 'Сумма {nix.BigInt} в копейках';

	 ## Пример сгенерированной структуры

	 Таблица message (MySQL):

		CREATE TABLE message (
		  id BIGINT(20) UNSIGNED NOT NULL AUTO_INCREMENT,
		  payload BLOB DEFAULT NULL,
		  amount DECIMAL(20,0) NOT NULL COMMENT 'Сумма {nix.BigInt} в копейках',
		  ttl TIME NOT NULL COMMENT 'Время жизни {nix.Duration}',
		  tags SET('a','b') DEFAULT NULL,
		  created_at DATETIME NOT NULL,
		  attr JSON DEFAULT NULL,
		  ratio FLOAT NOT NULL,
		  cnt TINYINT(4) NOT NULL,
		  PRIMARY KEY (id)
		);

	 Команда генерации с переопределением поля payload через командную строку:

		//go:generate db2struct create "" "message" "types" "Message" "message_model.go" "payload:nix.UUID"

	 Результат генерации (фрагмент):

		type Message struct {
			ID        uint64          `db:"id"         gorm:"column:id;primaryKey;autoIncrement;not null;precision:20;type:BIGINT(20) UNSIGNED"` //
			Payload   nix.UUID        `db:"payload"    gorm:"column:payload;default:null;type:BLOB"` //
			Amount    nix.BigInt      `db:"amount"     gorm:"column:amount;not null;type:DECIMAL(20,0)"` // Сумма в копейках
			TTL       nix.Duration    `db:"ttl"        gorm:"column:ttl;not null;type:TIME"` // Время жизни
			Tags      nix.StringSlice `db:"tags"       gorm:"column:tags;default:null;type:SET('a','b')"` //
			CreatedAt time.Time       `db:"created_at" gorm:"column:created_at;not null;type:DATETIME"` //
			Attr      nix.RawMessage  `db:"attr"       gorm:"column:attr;default:null;type:JSON"` //
			Ratio     float32         `db:"ratio"      gorm:"column:ratio;not null;precision:12;type:FLOAT"` //
			Cnt       int8            `db:"cnt"        gorm:"column:cnt;not null;type:TINYINT(4)"` //
		}

	 Поле amount получило тип nix.BigInt из комментария колонки, поле ttl —
	 nix.Duration из комментария колонки, поле payload — nix.UUID из командной
	 строки, маркеры {...} удалены из комментариев. Импорты time и
	 github.com/webnice/nix/v2 добавлены автоматически по фактическим типам полей.

	 # Замечания

	   - Импорты сгенерированного файла формируются автоматически по фактическим
	     типам полей: "encoding/json" (json.RawMessage), "time" (time.Time,
	     time.Duration), "github.com/webnice/nix/v2" (nix.*).
	   - Тег gorm:"type:..." формируется по реальному типу колонки БД и от
	     переопределений не зависит.
	   - Теги структуры формируются по документации GORM v2 (gorm.io/gorm):
	     column, primaryKey, autoIncrement, not null, default, size, precision,
	     scale, type. Тег db формируется для database/sql и sqlx.
	   - nix.Duration нативно разбирает формат времени баз данных начиная с
	     nix/v2 v2.0.2; nix.StringSlice для SET добавлен в nix/v2 v2.1.0.

*/

